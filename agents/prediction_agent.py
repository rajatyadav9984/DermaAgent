"""
DermaAgent - Prediction Agent
Processes raw multimodal model disease prediction and formats top-k results.
"""

import sys

# Ensure UTF-8 console output on Windows
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')


class PredictionAgent:

    def __init__(self):
        self.name = "PredictionAgent"

    def process(self, prediction_result):
        """
        Process the prediction generated by the ML model.
        """

        disease = prediction_result["disease"]
        confidence = prediction_result["confidence"]
        top3 = prediction_result["top3"]

        return {
            "agent": self.name,
            "disease": disease,
            "confidence": confidence,
            "top3": top3
        }


if __name__ == "__main__":
    agent = PredictionAgent()
    sample_res = {
        "disease": "akiec",
        "confidence": 0.6073,
        "top3": [
            {"disease": "akiec", "confidence": 0.6073},
            {"disease": "bkl", "confidence": 0.1211},
            {"disease": "bcc", "confidence": 0.0767}
        ]
    }
    output = agent.process(sample_res)
    print("[INFO] PredictionAgent Output:")
    print(output)
